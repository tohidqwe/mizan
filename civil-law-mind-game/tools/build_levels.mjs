function drop(n,title,concept,memory,pairs,instruction='قطعات را روی خانه حقوقی درست رها کن.'){
  const targets=[...new Map(pairs.map(x=>[x[1],x[2]||x[1]])).entries()].map(([id,label])=>({id,label}));
  const pieces=pairs.map((x,i)=>({id:'p'+i,label:x[0],targetId:x[1]}));
  return {n,title,concept,memory,mechanic:'DROP',instruction,pieces,targets,nodes:[],edges:[]};
}
function lab(n,title,concept,memory,pairs,instruction='معامله را مونتاژ کن؛ هر جزء را در جای درست قرار بده.'){
  const x=drop(n,title,concept,memory,pairs,instruction); x.mechanic='LAB'; return x;
}
function chain(n,title,concept,memory,steps,instruction='زنجیره را با کشیدن قطعات به ترتیب منطقی بساز.'){
  const pairs=steps.map((label,i)=>[label,'s'+i,(i+1)+'. مرحله']);
  const x=drop(n,title,concept,memory,pairs,instruction); x.mechanic='CHAIN'; return x;
}
function link(n,title,concept,memory,labels,connections,instruction='بین گره‌هایی که رابطه حقوقی دارند با انگشت کابل بکش.'){
  const positions=[
    [.22,.20],[.78,.20],[.18,.52],[.82,.52],[.28,.82],[.72,.82]
  ];
  const nodes=labels.map((label,i)=>({id:'n'+i,label,x:positions[i][0],y:positions[i][1]}));
  const edges=connections.map(([a,b])=>({from:'n'+a,to:'n'+b}));
  return {n,title,concept,memory,mechanic:'LINK',instruction,pieces:[],targets:[],nodes,edges};
}

