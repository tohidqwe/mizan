import { chromium } from "playwright";
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const OUT = path.resolve("artifacts/civil-official-sources");
await mkdir(OUT, { recursive: true });

const SOURCES = [
  {
    id: "qavanin",
    authority: "معاونت حقوقی ریاست جمهوری / سامانه ملی قوانین و مقررات",
    url: "https://qavanin.ir/Law/TreeText/178971",
    required: true,
    minChars: 30000,
  },
  {
    id: "majlis",
    authority: "مرکز پژوهش‌های مجلس شورای اسلامی",
    url: "https://rc.majlis.ir/fa/law/show/97937",
    required: true,
    minChars: 30000,
  },
  {
    id: "official-gazette",
    authority: "روزنامه رسمی جمهوری اسلامی ایران",
    url: "https://rrk.ir/",
    required: true,
    minChars: 100,
  },
  {
    id: "gov-pdf-host",
    authority: "شرکت آب و فاضلاب استان ایلام (دامنه دولتی؛ نسخه کمکی)",
    url: "https://www.abfa-ilam.ir/file_bank/1398/113981028-%D9%85%D8%AA%D9%86-%DA%A9%D8%A7%D9%85%D9%84-%D9%82%D8%A7%D9%86%D9%88%D9%86-%D9%85%D8%AF%D9%86%DB%8C.pdf",
    required: false,
    binary: true,
  },
];

const persianDigitMap = new Map([
  ["۰", "0"], ["۱", "1"], ["۲", "2"], ["۳", "3"], ["۴", "4"],
  ["۵", "5"], ["۶", "6"], ["۷", "7"], ["۸", "8"], ["۹", "9"],
]);

function toAsciiDigits(value) {
  return value.replace(/[۰-۹]/g, (x) => persianDigitMap.get(x) ?? x);
}

function normalizeForHash(value) {
  return toAsciiDigits(value)
    .normalize("NFKC")
    .replace(/ي/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/\u200c/g, " ")
    .replace(/[\s\u00a0]+/g, " ")
    .trim();
}

function articleNumbers(text) {
  const normalized = toAsciiDigits(text);
  const matches = [...normalized.matchAll(/ماده\s*([0-9]{1,4})(?:\s*(مکرر))?/g)];
  const base = new Set();
  const supplements = [];
  for (const m of matches) {
    const n = Number(m[1]);
    if (!Number.isInteger(n) || n < 1 || n > 1335) continue;
    if (m[2]) supplements.push(`${n} مکرر`);
    else base.add(n);
  }
  return { base: [...base].sort((a, b) => a - b), supplements: [...new Set(supplements)] };
}

const report = {
  retrievedAt: new Date().toISOString(),
  policy: "No legal text is generated by AI. Official-source retrieval failures keep the release gate closed.",
  sources: [],
};

const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ locale: "fa-IR" });

let hardFailure = false;
for (const source of SOURCES) {
  const item = { id: source.id, authority: source.authority, url: source.url, required: source.required };
  try {
    if (source.binary) {
      const response = await fetch(source.url, { redirect: "follow" });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const bytes = Buffer.from(await response.arrayBuffer());
      if (bytes.length < 10000) throw new Error(`PDF unexpectedly small: ${bytes.length} bytes`);
      await writeFile(path.join(OUT, `${source.id}.pdf`), bytes);
      item.bytes = bytes.length;
      item.sha256 = createHash("sha256").update(bytes).digest("hex");
      item.ok = true;
    } else {
      const page = await context.newPage();
      await page.goto(source.url, { waitUntil: "domcontentloaded", timeout: 60000 });
      await page.waitForTimeout(5000);
      const text = (await page.locator("body").innerText()).trim();
      const html = await page.content();
      await writeFile(path.join(OUT, `${source.id}.txt`), text, "utf8");
      await writeFile(path.join(OUT, `${source.id}.html`), html, "utf8");
      const normalized = normalizeForHash(text);
      const nums = articleNumbers(text);
      item.finalUrl = page.url();
      item.title = await page.title();
      item.characters = text.length;
      item.normalizedSha256 = createHash("sha256").update(normalized, "utf8").digest("hex");
      item.baseArticleNumbersSeen = nums.base.length;
      item.firstBaseArticle = nums.base[0] ?? null;
      item.lastBaseArticle = nums.base.at(-1) ?? null;
      item.supplementsSeen = nums.supplements;
      item.ok = text.length >= (source.minChars ?? 1);
      if (!item.ok) item.error = `Retrieved body too small (${text.length} chars). Likely redirect/block page.`;
      await page.close();
    }
  } catch (error) {
    item.ok = false;
    item.error = error instanceof Error ? error.message : String(error);
  }
  if (source.required && !item.ok) hardFailure = true;
  report.sources.push(item);
}

await browser.close();
await writeFile(path.join(OUT, "source-report.json"), JSON.stringify(report, null, 2), "utf8");
console.log(JSON.stringify(report, null, 2));

if (hardFailure) {
  console.error("OFFICIAL_SOURCE_GATE_CLOSED: one or more required official sources were not retrieved reliably.");
  process.exitCode = 2;
}
